import {act, renderHook, waitFor} from "@testing-library/react";
import {afterEach, describe, expect, it, vi} from "vitest";
import {useAnnotationFrames} from "./useAnnotationFrames";
import type {Annotation} from "@/features/koreader/api";
const base = `${window.location.origin}/epub/`;
const item: Annotation = {id: "a", bookId: "book", quote: "A quote", note: "", color: "yellow", anchor: {version: 1, href: "one.xhtml", exact: "A quote"}, deleted: false, revision: "1", updatedAt: ""};
afterEach(() => { document.querySelectorAll("iframe").forEach(frame => frame.remove()); });
function frame(href: string, text: string) {
    const iframe = document.createElement("iframe");
    iframe.src = `${base}${href}`;
    document.body.appendChild(iframe);
    const wnd = iframe.contentWindow!;
    wnd.document.open(); wnd.document.write(`<html><head></head><body><p>${text}</p></body></html>`); wnd.document.close();
    return wnd;
}
describe("documented EPUB frame integration", () => {
    it("renders exact ranges on chapter registration, refreshes style and removes tombstones", async () => {
        const wnd = frame("one.xhtml", "A quote");
        const set = vi.fn(), remove = vi.fn();
        Object.defineProperty(wnd, "CSS", {value: {highlights: {set, delete: remove}}});
        Object.defineProperty(wnd, "Highlight", {value: class {}});
        const ref = {current: base};
        const {result, rerender, unmount} = renderHook(({items, theme}) => useAnnotationFrames(items, ref, theme), {initialProps: {items: [item], theme: "light"}});
        act(() => result.current.register(wnd));
        await waitFor(() => expect(result.current.resolution.a).toBe("Highlighted in open chapter"));
        expect(set).toHaveBeenCalledTimes(7);
        rerender({items: [{...item, color: "green"}], theme: "dark"});
        await waitFor(() => expect(set).toHaveBeenCalledTimes(14));
        expect(wnd.document.querySelectorAll("[data-homebranch-annotations]")).toHaveLength(1);
        rerender({items: [], theme: "dark"});
        await waitFor(() => expect(result.current.resolution.a).toBeUndefined());
        unmount();
        expect(wnd.document.querySelector("[data-homebranch-annotations]")).toBeNull();
        expect(remove).toHaveBeenCalled();
    });
    it("never attaches a quote from another resource and reports unsupported rendering", async () => {
        const wnd = frame("two.xhtml", "A quote");
        const ref = {current: base};
        const {result} = renderHook(() => useAnnotationFrames([item], ref, "light"));
        act(() => result.current.register(wnd));
        await waitFor(() => expect(result.current.resolution.a).toBe("Not in an open chapter"));
        const correct = frame("one.xhtml", "A quote");
        act(() => result.current.register(correct));
        await waitFor(() => expect(result.current.resolution.a).toContain("cannot render"));
    });
    it("captures active selections and cleans up the frame on unload", async () => {
        const wnd = frame("one.xhtml", "Before A quote after");
        const ref = {current: base};
        const items: Annotation[] = [];
        const {result} = renderHook(() => useAnnotationFrames(items, ref, "light"));
        act(() => result.current.register(wnd));
        const range = wnd.document.createRange();
        range.setStart(wnd.document.querySelector("p")!.firstChild!, 7);
        range.setEnd(wnd.document.querySelector("p")!.firstChild!, 14);
        wnd.getSelection()!.addRange(range);
        act(() => wnd.document.dispatchEvent(new Event("selectionchange")));
        expect(result.current.selection?.exact).toBe("A quote");
        const swipe = vi.fn();
        wnd.addEventListener("touchmove", swipe);
        const move = new Event("touchmove", {bubbles: true, cancelable: true});
        wnd.document.body.dispatchEvent(move);
        expect(swipe).not.toHaveBeenCalled();
        expect(move.defaultPrevented).toBe(false);
        wnd.getSelection()!.removeAllRanges();
        wnd.document.body.dispatchEvent(new Event("touchstart", {bubbles: true}));
        wnd.document.body.dispatchEvent(new Event("touchmove", {bubbles: true}));
        expect(swipe).toHaveBeenCalledOnce();
        wnd.removeEventListener("touchmove", swipe);
        act(() => wnd.dispatchEvent(new Event("unload")));
        expect(result.current.selection).toBeNull();
    });
    it("derives a quote jump from verified live range geometry, never fuzzy locator text", () => {
        const wnd = frame("one.xhtml", "Before A quote after");
        const doc = wnd.document;
        Object.defineProperty(doc, "scrollingElement", {value: doc.documentElement});
        Object.defineProperty(doc.documentElement, "scrollWidth", {value: 2000});
        Object.defineProperty(doc.documentElement, "offsetHeight", {value: 4000});
        Object.defineProperty(wnd, "scrollX", {value: 300});
        Object.defineProperty(wnd, "scrollY", {value: 500});
        Object.defineProperty(wnd, "innerHeight", {value: 1000});
        Object.defineProperty((wnd as Window & typeof globalThis).Range.prototype, "getBoundingClientRect", {configurable: true, value: () => ({left: 100, top: 1500})});
        const ref = {current: base};
        const {result} = renderHook(() => useAnnotationFrames([item], ref, "light"));
        act(() => result.current.register(wnd));
        expect(result.current.locate(item, false)).toBe(0.2);
        expect(result.current.locate(item, true)).toBe(0.375);
        expect(result.current.locate({...item, anchor: {...item.anchor, exact: "Missing quote"}}, false)).toBeNull();
        expect(result.current.locate({...item, anchor: {...item.anchor, href: "two.xhtml"}}, false)).toBeNull();
    });
    it("registers cached iframe DOM lifecycles without a frameLoaded replay and cleans removed frames", async () => {
        const wnd = frame("one.xhtml", "A quote");
        const iframe = wnd.frameElement as HTMLIFrameElement;
        iframe.className = "readium-navigator-iframe";
        const root = document.createElement("div");
        document.body.appendChild(root);
        const remove = vi.fn();
        Object.defineProperty(wnd, "CSS", {value: {highlights: {set: vi.fn(), delete: remove}}});
        Object.defineProperty(wnd, "Highlight", {value: class {}});
        const ref = {current: base};
        const container = {current: root};
        const {result, unmount} = renderHook(() => useAnnotationFrames([item], ref, "light", container));
        act(() => { root.appendChild(iframe); });
        // Moving an iframe reloads its document; restore its fixture after that load.
        const current = iframe.contentWindow!;
        current.document.open(); current.document.write("<html><head></head><body><p>A quote</p></body></html>"); current.document.close();
        Object.defineProperty(current, "CSS", {configurable: true, value: {highlights: {set: vi.fn(), delete: remove}}});
        Object.defineProperty(current, "Highlight", {configurable: true, value: class {}});
        act(() => iframe.dispatchEvent(new Event("load")));
        await waitFor(() => expect(result.current.resolution.a).toBe("Highlighted in open chapter"));
        act(() => iframe.remove());
        await waitFor(() => expect(result.current.resolution.a).toBe("Not in an open chapter"));
        expect(remove).toHaveBeenCalled();
        unmount(); root.remove();
    });
});
